function buildPhraseMap(language) {
  const map = {};
  const current = DICTIONARY[language];
  const other = DICTIONARY[language === "EN" ? "ID" : "EN"];
  Object.keys(current).forEach((key) => {
    const from = other[key];
    const to = current[key];
    if (from && to && from !== to) map[from] = to;
  });
  return map;
}

function translateDom(language) {
  if (typeof document === "undefined") return;
  const map = buildPhraseMap(language);
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  const nodes = [];
  let node;
  while ((node = walker.nextNode())) nodes.push(node);
  nodes.forEach((textNode) => {
    const parent = textNode.parentElement;
    if (!parent || ["SCRIPT", "STYLE", "NOSCRIPT"].includes(parent.tagName)) return;
    const raw = textNode.nodeValue;
    const trimmed = raw.trim();
    if (!trimmed) return;
    const normalized = trimmed.replace(/\s+/g, " ");
    const translated = map[trimmed] || map[normalized];
    if (translated) textNode.nodeValue = raw.replace(trimmed, translated);
  });
  const elements = document.querySelectorAll("input[placeholder], textarea[placeholder], [title], [aria-label]");
  elements.forEach((el) => {
    ["placeholder", "title", "aria-label"].forEach((attr) => {
      const value = el.getAttribute(attr);
      if (value && map[value]) el.setAttribute(attr, map[value]);
    });
  });
}

export function LanguageProvider({ children }) {
  const [language, setLanguageState] = useState(() => {
    if (typeof window === "undefined") return "EN";
    return localStorage.getItem("trading_journal_language") === "ID" ? "ID" : "EN";
  });

  function setLanguage(next) {
    const value = next === "ID" ? "ID" : "EN";
    setLanguageState(value);
    if (typeof window !== "undefined") localStorage.setItem("trading_journal_language", value);
    if (typeof document !== "undefined") document.documentElement.lang = value.toLowerCase();
  }

  useEffect(() => {
    if (typeof document === "undefined") return undefined;
    document.documentElement.lang = language.toLowerCase();
    let translating = false;
    const run = () => {
      if (translating) return;
      translating = true;
      try { translateDom(language); } finally { translating = false; }
    };
    run();
    const observer = new MutationObserver(() => run());
    observer.observe(document.body, { childList: true, subtree: true, characterData: true });
    return () => observer.disconnect();
  }, [language]);

  const value = useMemo(() => ({
    language,
    setLanguage,
    t: (key) => DICTIONARY[language]?.[key] ?? DICTIONARY.EN[key] ?? key,
  }), [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

